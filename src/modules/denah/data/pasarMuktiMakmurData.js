function parseRawCSV(csvString, defaultCategoryName) {
  const lines = csvString.trim().split('\n');
  const items = [];
  const blockXMap = {};
  const blockRowMap = {};

  lines.forEach((line, index) => {
    if (index === 0 || !line.trim()) return;
    const cols = line.split(',');
    if (cols.length < 3) return;

    const blok = cols[1]?.trim() || `K-${index}`;
    const nama = cols[2]?.trim() || 'KOSONG';
    const nik = cols[3]?.trim() || '-';
    const alamat = cols[4]?.trim() || '-';
    const jenisUsaha = cols[5]?.trim() || defaultCategoryName;
    const luasDimensi = cols[6]?.trim() || '200 x 200';
    const luasM2 = cols[7]?.trim() || '4.0';
    const kategori = cols[8]?.trim() || 'LOS';
    const nilaiSewaStr = cols[9]?.trim() || '225000';
    const noHp = cols[10]?.trim() || '';

    const isKosong = nama.toUpperCase().includes('KOSONG') || nama === '' || nama === '-';
    const hasHp = noHp && noHp.length > 5;
    
    let status = 'terisi';
    if (isKosong) {
      status = 'kosong';
    } else if (hasHp) {
      status = 'terisi';
    }

    const blockLetter = blok.charAt(0).toUpperCase();
    if (!blockRowMap[blockLetter]) {
      const charCode = blockLetter.charCodeAt(0) - 65; // A=0, B=1...
      blockRowMap[blockLetter] = 40 + (charCode * 110);
      blockXMap[blockLetter] = 40;
    }

    const currentX = blockXMap[blockLetter];
    const currentY = blockRowMap[blockLetter];

    blockXMap[blockLetter] += 110;

    const nilaiNum = parseInt(nilaiSewaStr.replace(/[^0-9]/g, '')) || 225000;
    const sewaFormatted = `Rp ${nilaiNum.toLocaleString('id-ID')}/thn`;

    items.push({
      id: blok,
      nama: `Blok ${blok}`,
      shape_type: 'rect',
      x: currentX,
      y: currentY,
      width: 100,
      height: 80,
      status: status,
      pedagang: isKosong ? '-' : nama,
      nik: nik,
      alamat: alamat,
      kategori: jenisUsaha || defaultCategoryName,
      tipeKios: kategori,
      luasDimensi: luasDimensi,
      luasM2: luasM2,
      sewaBerakhir: '2026-12-31',
      sewaBulanan: sewaFormatted,
      nomorHp: noHp,
      qrCode: `QR-${blok}`
    });
  });

  return items;
}

